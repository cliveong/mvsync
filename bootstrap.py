#!/usr/bin/env python3
"""Portable bootstrap for mvsync.

Runs on any base Python (3.10+) interpreter; it does not need the project venv.
Idempotent: safe to run on every launch. It:

1. Ensures .venv exists and is healthy (recreates it when broken).
2. Installs dependencies whenever the requirement files change (hash-marked).
3. Resolves external tools (yt-dlp, mpv, ffmpeg): project tools/ first, then
   PATH, downloading portable copies into tools/ when they are missing.
4. Writes a project-local mpv config so your global mpv setup never leaks in.

Usage:
    python bootstrap.py [--check] [--force-deps] [--skip-tools]

Exit codes: 0 = ok (or check passed), 1 = failure.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "src"))

from mvsync import paths  # noqa: E402  (stdlib-only module)

VENV_DIR = ROOT / ".venv"
VENV_PYTHON = VENV_DIR / "Scripts" / "python.exe"
DEPS_MARKER = VENV_DIR / ".deps-ok"
REQUIREMENTS = ("requirements.txt", "requirements-dev.txt")
YTDLP_URL = "https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp.exe"
MPV_RSS_URL = "https://sourceforge.net/projects/mpv-player-windows/rss?path=/release"
USER_AGENT = "mvsync-bootstrap"

MPV_CONF = """\
# Project-local mpv config generated by bootstrap.py. Your global mpv config
# is intentionally not used so this project behaves the same everywhere.
ytdl=yes
script-opts=ytdl_hook-ytdl_path={ytdlp}
ytdl-format=bestvideo+bestaudio/best
keep-open=no
"""


def log(message: str) -> None:
    print(f"[bootstrap] {message}")


def run(cmd: list[str], **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, **kwargs)


def venv_python_ok(python: Path) -> bool:
    if not python.is_file():
        return False
    proc = run(
        [str(python), "-c", "import sys; print('%d.%d' % sys.version_info[:2])"],
        capture_output=True,
        text=True,
    )
    return proc.returncode == 0


def ensure_venv() -> Path:
    if venv_python_ok(VENV_PYTHON):
        proc = run([str(VENV_PYTHON), "-m", "pip", "--version"], capture_output=True, text=True)
        if proc.returncode == 0:
            return VENV_PYTHON
        log("venv pip is broken; recreating venv")
    if VENV_DIR.exists():
        log(f"recreating venv at {VENV_DIR}")
        shutil.rmtree(VENV_DIR, ignore_errors=True)
    log(f"creating venv with {sys.executable}")
    run([sys.executable, "-m", "venv", str(VENV_DIR)], check=True)
    return VENV_PYTHON


def requirements_fingerprint() -> str:
    digest = hashlib.sha256()
    digest.update(f"py{sys.version_info[0]}.{sys.version_info[1]}".encode())
    for name in REQUIREMENTS:
        path = ROOT / name
        digest.update(name.encode())
        if path.is_file():
            digest.update(path.read_bytes())
    return digest.hexdigest()


def deps_are_current() -> bool:
    if not DEPS_MARKER.is_file():
        return False
    return DEPS_MARKER.read_text(encoding="utf-8").strip() == requirements_fingerprint()


def ensure_deps(python: Path, force: bool) -> None:
    if not force and deps_are_current():
        return
    log("installing dependencies (first run takes a few minutes)")
    run(
        [str(python), "-m", "pip", "install", "--disable-pip-version-check", "--upgrade", "pip"],
        check=True,
    )
    args = [
        str(python),
        "-m",
        "pip",
        "install",
        "--disable-pip-version-check",
        "-r",
        str(ROOT / REQUIREMENTS[0]),
    ]
    dev = ROOT / REQUIREMENTS[1]
    if dev.is_file():
        args += ["-r", str(dev)]
    run(args, check=True)
    freeze = run([str(python), "-m", "pip", "freeze"], capture_output=True, text=True, check=True)
    (ROOT / "requirements.lock").write_text(freeze.stdout, encoding="utf-8")
    DEPS_MARKER.write_text(requirements_fingerprint(), encoding="utf-8")


def download(url: str, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_suffix(dest.suffix + ".part")
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response, open(part, "wb") as handle:
        shutil.copyfileobj(response, handle)
    os.replace(part, dest)


def ensure_ytdlp(check_only: bool = False) -> Path | None:
    existing = paths.find_tool("yt-dlp", ROOT)
    if existing:
        return existing
    if check_only:
        return None
    log("downloading portable yt-dlp.exe into tools/")
    dest = paths.tools_dir(ROOT) / "yt-dlp.exe"
    download(YTDLP_URL, dest)
    return dest


def latest_mpv_url() -> str:
    request = urllib.request.Request(MPV_RSS_URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        tree = ET.parse(response)
    for item in tree.iter("item"):
        link = (item.findtext("link") or "").strip()
        if not link:
            continue
        parts = [p for p in link.split("/") if p]
        filename = next((p for p in reversed(parts) if p.endswith(".7z")), "")
        stem = filename.removesuffix(".7z")
        if not stem.startswith("mpv-"):
            continue
        if any(tag in stem for tag in ("-v3", "i686", "aarch64")):
            continue
        if stem.endswith("-x86_64") or "-x86_64-" in stem:
            return link
    raise RuntimeError("no mpv-x86_64 release found in SourceForge feed")


def ensure_mpv(check_only: bool = False) -> Path | None:
    existing = paths.find_tool("mpv", ROOT)
    if existing:
        return existing
    if check_only:
        return None
    log("mpv not found; downloading portable build into tools/mpv")
    try:
        url = latest_mpv_url()
        archive = paths.tools_dir(ROOT) / ".download" / "mpv.7z"
        download(url, archive)
        target = paths.tools_dir(ROOT) / "mpv"
        shutil.rmtree(target, ignore_errors=True)
        target.mkdir(parents=True, exist_ok=True)
        proc = run(["tar", "-xf", str(archive), "-C", str(target)], capture_output=True, text=True)
        if proc.returncode != 0 or not (target / "mpv.exe").is_file():
            raise RuntimeError(proc.stderr.strip() or "tar extraction produced no mpv.exe")
        archive.unlink(missing_ok=True)
        return target / "mpv.exe"
    except Exception as exc:  # noqa: BLE001 - report and continue with a warning
        log(f"mpv download failed: {exc}")
        log("install mpv manually (winget install shinchiro.mpv) or drop mpv.exe into tools\\mpv\\")
        return None


def ensure_ffmpeg(check_only: bool = False) -> Path | None:
    tool = paths.find_tool("ffmpeg", ROOT)
    if tool:
        return tool
    if not check_only:
        log("ffmpeg missing; install with: winget install Gyan.FFmpeg")
    return None


def ensure_mpv_config(ytdlp: Path | None) -> Path:
    config_dir = paths.ensure_dir(paths.mpv_config_dir(ROOT))
    conf = config_dir / "mpv.conf"
    ytdlp_value = str(ytdlp).replace("\\", "/") if ytdlp else "yt-dlp"
    content = MPV_CONF.format(ytdlp=ytdlp_value)
    if not conf.is_file() or conf.read_text(encoding="utf-8") != content:
        conf.write_text(content, encoding="utf-8")
    return conf


def report_status() -> int:
    ok_venv = venv_python_ok(VENV_PYTHON)
    ok_deps = ok_venv and deps_are_current()
    log(f"venv: {'ok' if ok_venv else 'missing'}")
    log(f"deps: {'ok' if ok_deps else 'stale'}")
    ok_tools = True
    for name in ("yt-dlp", "mpv", "ffmpeg", "ffprobe"):
        tool = paths.find_tool(name, ROOT)
        if tool is None:
            ok_tools = False
        log(f"{name}: {tool if tool else 'MISSING'}")
    ready = ok_venv and ok_deps and ok_tools
    log("ready" if ready else "not ready")
    return 0 if ready else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="report status only, change nothing")
    parser.add_argument("--force-deps", action="store_true", help="reinstall dependencies")
    parser.add_argument("--skip-tools", action="store_true", help="do not touch tools/")
    args = parser.parse_args(argv)

    if args.check:
        return report_status()

    try:
        python = ensure_venv()
        ensure_deps(python, args.force_deps)
        ytdlp = None
        mpv = None
        if not args.skip_tools:
            ytdlp = ensure_ytdlp()
            mpv = ensure_mpv()
            ensure_mpv_config(ytdlp)
        ffmpeg = ensure_ffmpeg()
        ready = all((ytdlp, mpv, ffmpeg))
        log("ready" if ready else "ready with warnings (see above)")
        return 0
    except subprocess.CalledProcessError as exc:
        log(f"command failed: {' '.join(map(str, exc.cmd))}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
